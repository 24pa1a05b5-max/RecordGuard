    final contradictionCount = effectiveFindings.where((f) => f.classification == 'POTENTIAL_CONTRADICTION').length;

    return Comparison(
      id: "CMP-${patientId.replaceAll('PAT-', '')}-${DateTime.now().millisecondsSinceEpoch % 10000}",
      patientId: patientId,
      documentAId: "DOC-$patientId-A",
      documentBId: "DOC-$patientId-B",
      documentAName: "Baseline Clinical Record ($docAType)",
      documentBName: "Subsequent Clinical Record ($docBType)",
      title: "Reconciliation: $docAType vs $docBType",
      status: "COMPLETED",
      totalFindings: effectiveFindings.length,
      contradictionCount: contradictionCount,
      createdAt: DateTime.now().toIso8601String(),
      findings: effectiveFindings,
    );
  }

